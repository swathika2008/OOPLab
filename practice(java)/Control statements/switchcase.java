//SWITCH CASE
class switchcase {
    public static void main(String[] args) {
int a = 7;
int b = 18;
char op = '-';
switch (op){
case '+':System.out.println(a+b);break;
case '-':System.out.println(a-b);break;
case '*':System.out.println(a*b);break;
case '/':System.out.println(a/b);break;

}
}
}